function buildInitialTelemetryForFeeder(feeder: Feeder): TelemetryLogEntry[] {
  const genesisPrev = sha256Hex(`GENESIS|${feeder.id}`);
  const samplePattern: Array<{ state: PowerState; v: number; hz: number; crowd: number }> =
    feeder.id === 'feeder-aroma-02'
      ? [
          { state: 'ON', v: 223.1, hz: 50.02, crowd: 1 },
          { state: 'ON', v: 220.4, hz: 50.0, crowd: 0 },
          { state: 'LOW_VOLTAGE', v: 184.2, hz: 49.6, crowd: 3 },
          { state: 'ON', v: 219.5, hz: 49.99, crowd: 1 },
          { state: 'ON', v: 221.6, hz: 50.01, crowd: 0 },
        ]
      : feeder.id === 'feeder-eke-05'
      ? [
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 6 },
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 4 },
          { state: 'LOW_VOLTAGE', v: 164.0, hz: 49.42, crowd: 5 },
          { state: 'ON', v: 216.3, hz: 49.95, crowd: 2 },
          { state: 'ON', v: 217.8, hz: 49.98, crowd: 1 },
        ]
      : feeder.id === 'feeder-zik-03'
      ? [
          { state: 'ON', v: 214.0, hz: 49.94, crowd: 1 },
          { state: 'LOW_VOLTAGE', v: 162.8, hz: 49.4, crowd: 4 },
          { state: 'LOW_VOLTAGE', v: 155.9, hz: 49.31, crowd: 7 },
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 8 },
          { state: 'LOW_VOLTAGE', v: 158.4, hz: 49.35, crowd: 5 },
        ]
      : [
          { state: 'ON', v: 212.5, hz: 49.9, crowd: 1 },
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 9 },
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 6 },
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 4 },
          { state: 'OFF', v: 0.0, hz: 0.0, crowd: 3 },
        ];

  const baseEpoch = Date.parse('2026-11-18T12:55:00Z');
  const entries: TelemetryLogEntry[] = [];
  let prevHash = genesisPrev;

  samplePattern.forEach((step, idx) => {
    const seq = 1041 + idx;
    const recordedAt = new Date(baseEpoch + idx * 5 * 60 * 1000).toISOString();
    const payloadHash = computePayloadHash({
      feederId: feeder.id,
      recordedAt,
      voltageL1V: step.v,
      frequencyHz: step.hz,
      rawDeviceState: step.state,
    });
    const chainHash = computeChainHash({
      prevHash,
      feederId: feeder.id,
      sequenceNo: seq,
      recordedAt,
      consensusState: step.state,
      voltageL1V: step.v,
      payloadHash,
    });

    entries.push({
      feederId: feeder.id,
      sequenceNo: seq,
      recordedAt,
      consensusState: step.state,
      rawDeviceState: step.state,
      voltageL1V: step.v,
      frequencyHz: step.hz,
      intervalSeconds: 300,
      supplyCreditedSec: step.state === 'ON' ? 300 : step.state === 'LOW_VOLTAGE' ? 150 : 0,
      consensusConfidence: step.crowd >= 4 ? 0.97 : 0.91,
      crowdConfirmCount: step.crowd,
      prevHash,
      payloadHash,
      chainHash,
      signingKeyId: 'ACTDA-ED25519-KEY-2026',
    });

    prevHash = chainHash;
  });

  return entries;
}

